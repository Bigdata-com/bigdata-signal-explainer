"""Markdown export of a run — the version that gets pasted into an email, Teams, ChatGPT or Claude."""
from __future__ import annotations

from datetime import date, timedelta

from .analysis import describe_move


def windows(f: dict) -> dict:
    """The explained window and the prior window it is compared with, as readable date ranges."""
    w = f["window"]
    start = date.fromisoformat(w["start"])
    prior_start = date.fromisoformat(w.get("prior_start") or (start - timedelta(days=w["days"])).isoformat())
    fmt = lambda a, b: f"{a:%b %-d} → {b:%b %-d, %Y}"  # noqa: E731
    return {"now": fmt(start, date.fromisoformat(w["end"])),
            "prior": fmt(prior_start, start - timedelta(days=1))}


def to_markdown(run: dict, base_url: str = "") -> str:
    f, n = run["facts"], run["narrative"]
    m, c, w = f["move"], f["company"], f["window"]
    ev = {e["id"]: e for e in f["attribution"]["evidence"]}
    titles = {d["key"]: d for d in n.get("drivers", [])}
    window = (f"since the {w['earnings_call']['date']} earnings call" if w.get("earnings_call")
              else f"{w['days']}-day lookback")
    ws = windows(f)
    out = [
        f"# {c['name']} ({c.get('ticker') or c['id']}) — {n['headline']}",
        f"*As of {f['as_of']} · {window} · tone: {n['tone']} · confidence: {n['confidence']}*",
        f"*Explaining **{ws['now']}**, compared with the prior window {ws['prior']}.*",
        "",
        f"**Signal:** daily sentiment {m['start_level']:+.2f} → {m['end_level']:+.2f} "
        f"(change {m['change']:+.3f}), {describe_move(m)}.",
        "",
        f"**Summary.** {n['summary']}",
        "",
        "## What happened",
        n["narrative"],
        "",
        "## What drove the change",
        "| Driver | Effect | Share of change | Articles (now / prior) | Why |",
        "|---|---|---|---|---|",
    ]
    for d in f["attribution"]["drivers"]:
        t = titles.get(d["key"], {})
        label = t.get("title") or d["label"]
        if d["reactive"]:
            label += " *(market reaction)*"
        effect = {"positive": "lifted", "negative": "weighed"}.get(d["direction"], "neutral")
        out.append(f"| {label} | {effect} ({d['impact']:+.3f}) | {d['share']:.0%} | "
                   f"{d['documents']} / {d['prior_documents']} | {(t.get('explanation') or '').replace('|', '/')} |")
    out += ["", "## Stock-specific or sector-wide?", n["stock_vs_sector"]]
    p = f.get("peers") or {}
    if p.get("available"):
        out.append("")
        out.append(f"Peer median change {p['peer_median_change']:+.3f} → stock-specific part "
                   f"{p['idiosyncratic_change']:+.3f} (**{p['verdict']}**). Peers: " +
                   ", ".join(f"{x['name']} ({x['change']:+.3f})" for x in p["peers"] if x.get("change") is not None))
    if n.get("thesis_drift"):
        out += ["", "## Since the last earnings call", n["thesis_drift"]]
    if n.get("what_to_watch"):
        out += ["", "## What to watch"] + [f"- {x}" for x in n["what_to_watch"]]
    if n.get("questions_for_management"):
        out += ["", "## Questions for management"] + [f"- {x}" for x in n["questions_for_management"]]
    new = [e for e in ev.values() if e.get("window") != "prior"]
    faded = [e for e in ev.values() if e.get("window") == "prior"]
    out += ["", f"## Evidence: new in this window ({ws['now']})"]
    out += [_ev_line(e) for e in new] or ["- None"]
    if faded:
        out += ["", f"## Evidence: faded since the prior window ({ws['prior']})",
                "*Stories that were in the news before the window and went quiet in it. Their absence moved the "
                "tone: faded good news weighs, faded bad news lifts.*"]
        out += [_ev_line(e) for e in faded]
    if f.get("management"):
        out += ["", "## Management on the earnings call"]
        out += [f"- **[{mm['id']}]** {mm['date']}: “{mm['text']}”" for mm in f["management"]]
    if n.get("caveats"):
        out += ["", f"*Caveats: {n['caveats']}*"]
    out += ["", f"*Source: [Bigdata.com](https://bigdata.com) entity sentiment and news analytics. "
                f"Narrative generated by {run.get('model')}." + (f" Report: {base_url}/runs/{run['id']}*" if base_url else "*")]
    return "\n".join(out)


def _ev_line(e: dict) -> str:
    link = f"[{e['headline']}]({e['url']})" if e.get("url") else e.get("headline") or ""
    return f"- **[{e['id']}]** {e['date']} · {e.get('source') or ''} · {link} (sentiment {e['sentiment']:+.2f})"
